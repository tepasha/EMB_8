#pragma once
#include <stdint.h>

/**
 * Компактний растровий шрифт 5x7 пікселів.
 * Підтримує лише символи, потрібні для виводу T/RH/P/DS18B20:
 * пробіл, цифри 0-9, '.', ':', '-', '%', 'B','C','D','H','P','R','S','T',
 * 'a', 'h' та символ градуса (код 0xB0, той самий байт, що дає "%c" з 0xB0).
 *
 * Формат: 5 байт на символ (по одному на стовпець), у кожному байті
 * біт 0 = верхній рядок пікселя, біт 6 = нижній (7 рядків використовується
 * з 8 можливих - нижній ряд завжди 0, це проміжок між рядками тексту).
 *
 * Повертає вказівник на 5-байтний гліф, або NULL для непідтримуваного символу
 * (у такому разі малюється пробіл).
 */
const uint8_t *font5x7_get_glyph(char c);
